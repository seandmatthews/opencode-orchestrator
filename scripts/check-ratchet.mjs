// The ratchet: finding→gate promotion proof (Gate 1.26, fast tier, T-041) —
// run under tsx:
//   node node_modules/tsx/dist/cli.mjs scripts/check-ratchet.mjs
// Zero model tokens, zero opencode involvement. The spec §32 ratchet
// (finding → reproduction → machine check → project quality suite) is
// HUMAN-OWNED and CROSSES RUNS (decisions.md, the 2026-10-21 T-039 entry):
// no engine code promotes anything — the promotion is a change-set to the
// fixture/gate set, and the promoted check then eliminates mechanically,
// forever. This check re-proves that end to end on the demo fixture class,
// token-free:
//   S1  the PRE-promotion fixture, built from verbatim pre-promotion
//       literals (the demo-target content before T-041): baseline passes its
//       own gates and there is no clamp anywhere — the old-gates world.
//   S2  the POST-promotion fixture, generated by the REAL promoted
//       scripts/demo-target.mjs: baseline still passes its own gates
//       (AGENTS.md #7 applies to the fixture too), the promoted inverted-
//       bounds check is present (assert.throws RangeError), the guard is in
//       calc.js, and the finding's own diff NO LONGER APPLIES to it.
//   S3  the vendored finding (scripts/fixtures/t041-finding-diff.patch — the
//       byte-identical diff.patch of run 20261021225243 candidate c01, whose
//       verifier concern is the finding): it carries the UNGUARDED clamp
//       body, no guard — and it applies cleanly to the pre-promotion
//       fixture (it is that run's own candidate diff).
//   S4  RED BAR: a real-CLI --jobs run (machine worker applying the vendored
//       finding, gates build+test) against the pre-promotion fixture —
//       the candidate that breaks the (future) promoted check passes the
//       old gates and SURVIVES (passedAllGates true, diff > 0 — never a
//       NO-OP pass).
//   S5  GREEN BAR: the same-class candidate (machine worker stripping the
//       promoted guard) against the post-promotion fixture — ELIMINATED on
//       the promoted gate, the report's gate row citing name + command +
//       exitCode (the T-027 recorded-command property, cross-run).
// Both drives go through the REAL pipeline entry (src/cli.ts) with
// `worker: "machine"` jobs (the T-017 token-free end-to-end), sandbox run
// roots and sandbox DBs — no live store, no residue: the sandbox is removed
// at the end (AGENTS.md #10 mechanized). The one-time recorded proof runs
// this check mirrors are C:\swarm\20261021234438 (red) and
// C:\swarm\20261021234632 (green) — recorded in VERIFICATION.md's ratchet
// section; the fast tier never reads them back.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const failures = []
const t = (name, cond) => {
  console.log(`${cond ? 'ok' : 'FAIL'}: ${name}`)
  if (!cond) failures.push(name)
}
const read = (p) => readFileSync(p, 'utf8')

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const sandbox = 'C:/swarm/verify-ratchet'
const NODE = process.execPath
const IDENTITY = ['-c', 'user.name=check-ratchet', '-c', 'user.email=ratchet@local']
const NODE_EXE = NODE.replaceAll('\\', '/')
const RED_WORKER = join(root, 'scripts', 'fixtures', 't041-worker-red.mjs')
const GREEN_WORKER = join(root, 'scripts', 'fixtures', 't041-worker-green.mjs')
const FINDING_PATCH = join(root, 'scripts', 'fixtures', 't041-finding-diff.patch')
const DEMO_SCRIPT = join(root, 'scripts', 'demo-target.mjs')
const GATES = [
  { name: 'build', command: 'node build.js' },
  { name: 'test', command: 'node test.js' },
]

rmSync(sandbox, { recursive: true, force: true })
mkdirSync(sandbox, { recursive: true })

const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { encoding: 'utf8', windowsHide: true, ...opts })
const git = (repo, ...args) => run('git', ['-C', repo, ...args])

/** The verbatim PRE-promotion demo-target files (scripts/demo-target.mjs
 *  before T-041's promotion change-set — add() only, no clamp anywhere). */
const PRE_PROMOTION_FILES = {
  'package.json': JSON.stringify({ name: 'demo-target', private: true }, null, 2),
  'calc.js': `function add(a, b) {
  return a + b
}

module.exports = { add }
`,
  'build.js': `const { add } = require('./calc.js')
if (add(2, 3) !== 5) {
  console.error('build check failed')
  process.exit(1)
}
console.log('build ok')
`,
  'test.js': `const assert = require('node:assert')
const { add } = require('./calc.js')

assert.equal(add(1, 2), 3)
assert.equal(add(-1, 1), 0)
assert.equal(add(0, 0), 0)
console.log('tests ok')
`,
  '.gitignore': 'node_modules/\n',
}

function makeRepo(dir) {
  mkdirSync(dir, { recursive: true })
  for (const [name, content] of Object.entries(PRE_PROMOTION_FILES)) {
    writeFileSync(join(dir, name), content)
  }
  git(dir, 'init', '-b', 'main')
  git(dir, ...IDENTITY, 'add', '-A')
  git(dir, ...IDENTITY, 'commit', '-m', 'baseline: add() with build and test checks')
}

/** A real-CLI drive: `worker: "machine"` job + the demo gates, sandbox run
 *  root and sandbox DB (never the live store). Returns {code, out, runDir,
 *  report} — the drive exits 0 whenever the run completes mechanically; the
 *  VERDICT rides the report (an elimination is not a crash). */
function drive(label, workerScript, repo, runsDir, dbPath) {
  const specPath = join(sandbox, `${label}-jobs.json`)
  writeFileSync(specPath, JSON.stringify({
    phases: [{ id: 'main' }],
    jobs: [{
      id: 'c01',
      phase: 'main',
      dependencies: [],
      brief: `T-041 ratchet proof (${label}): the machine worker replays the promoted check's failure class — the unguarded clamp body the T-039-era verifier flagged in run 20261021225243. Provenance only — never interpreted or executed by this worker.`,
      worker: 'machine',
      command: [NODE_EXE, workerScript.replaceAll('\\', '/')],
      gates: GATES,
    }],
  }, null, 2))
  let code = 0
  let out = ''
  try {
    out = run(NODE, [
      join(root, 'node_modules', 'tsx', 'dist', 'cli.mjs'),
      join(root, 'src', 'cli.ts'),
      '--repo', repo,
      '--jobs', specPath,
      '--no-review',
      '--run-root', runsDir,
      '--db', dbPath,
      '--clean',
    ], { timeout: 120_000 })
  } catch (e) {
    code = e.status ?? -1
    out = `${e.stdout ?? ''}${e.stderr ?? e.message}`
  }
  if (code !== 0) console.error(`--- ${label} drive output (exit ${code}) ---\n${out}`)
  const runDirs = existsSync(runsDir) ? readdirSync(runsDir).filter((d) => /^\d{14}$/.test(d)) : []
  const runDir = runDirs.length === 1 ? join(runsDir, runDirs[0]) : null
  const report = runDir !== null ? JSON.parse(read(join(runDir, 'report.json'))) : null
  return { code, out, runDir, report }
}

const lockFilesIn = (dir) => {
  try {
    return readdirSync(join(dir, 'locks')).filter((f) => f.endsWith('.lock'))
  } catch {
    return []
  }
}

try {
  // ---------- S1: the pre-promotion fixture (the old-gates world) ----------
  const preRepo = join(sandbox, 'pre-promotion', 'demo-target')
  makeRepo(preRepo)
  let baseline
  try {
    baseline = run(NODE, ['build.js'], { cwd: preRepo }) + run(NODE, ['test.js'], { cwd: preRepo })
  } catch (e) {
    baseline = `FAILED: ${e.status ?? e.message}`
  }
  t('S1: the pre-promotion fixture baseline passes its own gates (build ok + tests ok)',
    baseline.includes('build ok') && baseline.includes('tests ok'))
  t('S1: the pre-promotion fixture has NO clamp anywhere (calc.js and test.js)',
    !read(join(preRepo, 'calc.js')).includes('clamp') && !read(join(preRepo, 'test.js')).includes('clamp'))

  // ---------- S2: the promoted fixture, from the REAL promoted script ----------
  const postRepo = join(sandbox, 'post-promotion', 'demo-target')
  let demoOut = ''
  let demoCode = 0
  try {
    demoOut = run(NODE, [DEMO_SCRIPT, postRepo], { cwd: root })
  } catch (e) {
    demoCode = e.status ?? -1
    demoOut = `${e.stdout ?? ''}${e.stderr ?? e.message}`
  }
  t('S2: node scripts/demo-target.mjs generates the promoted fixture green (exit 0, build ok + tests ok)',
    demoCode === 0 && demoOut.includes('build ok') && demoOut.includes('tests ok'))
  const postTest = read(join(postRepo, 'test.js'))
  const postCalc = read(join(postRepo, 'calc.js'))
  t('S2: the promoted check is IN the generated fixture — both inverted-bounds assertions present',
    postTest.includes('assert.throws(() => clamp(5, 10, 0), RangeError)')
    && postTest.includes('assert.throws(() => clamp(0, -5, -10), RangeError)'))
  t('S2: the promoted guard is IN the generated calc.js (lo > hi RangeError)',
    postCalc.includes('if (lo > hi)') && postCalc.includes('RangeError'))
  let appliesToPost = true
  try {
    git(postRepo, 'apply', '--check', FINDING_PATCH)
  } catch {
    appliesToPost = false
  }
  t('S2: the finding\'s own diff NO LONGER APPLIES to the promoted fixture (the fixture moved past the finding)',
    appliesToPost === false)

  // ---------- S3: the vendored finding is the T-039 candidate's unguarded ----------
  // ---------- clamp, and it applies to the pre-promotion fixture      ----------
  const finding = read(FINDING_PATCH)
  t('S3: the vendored finding diff carries the UNGUARDED clamp body and no guard',
    finding.includes('return Math.min(Math.max(v, lo), hi)') && !finding.includes('lo > hi'))
  let appliesToPre = false
  try {
    git(preRepo, 'apply', '--check', FINDING_PATCH)
    appliesToPre = true
  } catch { /* refused */ }
  t('S3: the vendored finding diff applies cleanly to the pre-promotion fixture (it is that era\'s candidate diff)',
    appliesToPre === true)

  // ---------- S4: RED BAR — the finding's candidate survives the old gates ----------
  const redRuns = join(sandbox, 'red', 'runs')
  const red = drive('red', RED_WORKER, preRepo, redRuns, join(sandbox, 'red', 'refinery.db'))
  t('S4: the red drive (real CLI) exits 0 — the run completes mechanically', red.code === 0)
  t('S4: exactly one run dir recorded', red.report !== null)
  const redC = red.report?.candidates?.[0]
  t('S4: RED BAR — the candidate breaking the promoted check PASSES the old gates and survives',
    redC?.workerOk === true && redC?.diffBytes > 0 && redC?.passedAllGates === true
    && redC?.error === undefined
    && redC?.gates?.length === 2 && redC.gates.every((g) => g.passed && g.exitCode === 0))
  t('S4: the old gates are the demo gates, commands recorded (T-027)',
    redC?.gates?.[0]?.name === 'build' && redC?.gates?.[0]?.command === 'node build.js'
    && redC?.gates?.[1]?.name === 'test' && redC?.gates?.[1]?.command === 'node test.js')
  t('S4: the surviving diff IS the finding — the unguarded clamp body (725 bytes, the T-039 candidate diff)',
    redC?.diffBytes === 725 && read(join(red.runDir, 'c01', 'diff.patch')).includes('return Math.min(Math.max(v, lo), hi)'))
  t('S4: the red drive left no residual lock (released on every path)', lockFilesIn(redRuns).length === 0)

  // ---------- S5: GREEN BAR — the same class eliminated on the promoted gate ----------
  const greenRuns = join(sandbox, 'green', 'runs')
  const green = drive('green', GREEN_WORKER, postRepo, greenRuns, join(sandbox, 'green', 'refinery.db'))
  t('S5: the green drive (real CLI) exits 0 — an ELIMINATION is a verdict, not a crash', green.code === 0)
  t('S5: exactly one run dir recorded', green.report !== null)
  const greenC = green.report?.candidates?.[0]
  t('S5: GREEN BAR — the same-class candidate is eliminated on the promoted gate',
    greenC?.workerOk === true && greenC?.diffBytes > 0 && greenC?.passedAllGates === false
    && greenC?.error === undefined)
  t('S5: the elimination cites gate name + command + exitCode (T-027, cross-run): test / node test.js / 1',
    greenC?.gates?.[0]?.name === 'build' && greenC?.gates?.[0]?.passed === true
    && greenC?.gates?.[1]?.name === 'test' && greenC?.gates?.[1]?.passed === false
    && greenC?.gates?.[1]?.exitCode === 1 && greenC?.gates?.[1]?.command === 'node test.js')
  t('S5: the failing output names the promoted check (the RangeError assertion)',
    (greenC?.gates?.[1]?.outputTail ?? '').includes('RangeError'))
  t('S5: the eliminated diff is the real regression — the guard stripped, never a NO-OP (AGENTS.md #7)',
    greenC?.diffBytes > 0
    && read(join(green.runDir, 'c01', 'diff.patch')).includes('-  if (lo > hi) {'))
  t('S5: the green drive left no residual lock (released on every path)', lockFilesIn(greenRuns).length === 0)
} finally {
  // tidy: the whole sandbox goes (AGENTS.md #10 mechanized for this check).
  rmSync(sandbox, { recursive: true, force: true })
}

console.log(`\n=== check-ratchet (Gate 1.26): ${failures.length === 0 ? 'ALL GREEN' : `${failures.length} failure(s)`} ===`)
process.exit(failures.length === 0 ? 0 : 1)
